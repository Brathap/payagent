'use client';

import React, { useState, useEffect, useMemo, useRef, useCallback } from 'react';
import { AgGridReact } from 'ag-grid-react';
import { ModuleRegistry, AllCommunityModule, ColDef } from 'ag-grid-community';

import 'ag-grid-community/styles/ag-grid.css';
import 'ag-grid-community/styles/ag-theme-quartz.css';

import {
  ShieldAlert,
  Sparkles,
  Download,
  Search,
  RefreshCw,
  FileText,
  DollarSign,
  TrendingUp,
  AlertTriangle,
  CheckCircle,
  Copy,
  Check,
  ShieldCheck,
  Zap,
  Play,
  Square,
  Radio,
} from 'lucide-react';
import { MerchantOrder } from '@/lib/types';
import { playSound } from '@/lib/sounds';

ModuleRegistry.registerModules([AllCommunityModule]);

interface MerchantDashboardProps {
  soundEnabled: boolean;
}

export default function MerchantDashboard({ soundEnabled }: MerchantDashboardProps) {
  const [orders, setOrders] = useState<MerchantOrder[]>([]);
  const [loading, setLoading] = useState(true);
  const [quickFilter, setQuickFilter] = useState('');
  const [selectedOrder, setSelectedOrder] = useState<MerchantOrder | null>(null);
  const [auditData, setAuditData] = useState<any>(null);
  const [auditing, setAuditing] = useState(false);
  const [generatedDispute, setGeneratedDispute] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  // Live Simulator State
  const [isLiveStreaming, setIsLiveStreaming] = useState(false);
  const streamTimerRef = useRef<NodeJS.Timeout | null>(null);

  const gridRef = useRef<AgGridReact>(null);

  const fetchOrders = useCallback(async () => {
    setLoading(true);
    try {
      const res = await fetch('/api/merchant/orders');
      const data = await res.json();
      setOrders(data.orders || []);
      if (data.orders?.length > 0 && !selectedOrder) {
        setSelectedOrder(data.orders[0]);
      }
    } catch (err) {
      console.error('Failed to fetch orders:', err);
    } finally {
      setLoading(false);
    }
  }, [selectedOrder]);

  useEffect(() => {
    fetchOrders();
  }, [fetchOrders]);

  // Live Transaction Stream Simulator
  useEffect(() => {
    if (isLiveStreaming) {
      streamTimerRef.current = setInterval(async () => {
        try {
          const res = await fetch('/api/merchant/simulate', { method: 'POST' });
          const json = await res.json();
          if (json.order) {
            setOrders((prev) => [json.order, ...prev]);
            if (soundEnabled) playSound('click');
          }
        } catch (e) {
          console.error('Stream simulation error:', e);
        }
      }, 3500);
    } else {
      if (streamTimerRef.current) clearInterval(streamTimerRef.current);
    }
    return () => {
      if (streamTimerRef.current) clearInterval(streamTimerRef.current);
    };
  }, [isLiveStreaming, soundEnabled]);

  const toggleLiveStream = () => {
    if (soundEnabled) playSound('click');
    setIsLiveStreaming((prev) => !prev);
  };

  const runAiAudit = async () => {
    setAuditing(true);
    if (soundEnabled) playSound('click');
    try {
      const res = await fetch('/api/merchant/audit', { method: 'POST' });
      const data = await res.json();
      setAuditData(data);
      if (soundEnabled) playSound('success');
    } catch (err) {
      console.error('Failed to run audit:', err);
      if (soundEnabled) playSound('alert');
    } finally {
      setAuditing(false);
    }
  };

  const handleExportCsv = () => {
    if (soundEnabled) playSound('click');
    gridRef.current?.api.exportDataAsCsv({
      fileName: `payagent-telemetry-${new Date().toISOString().substring(0, 10)}.csv`,
    });
  };

  const generateDisputeLetter = (order: MerchantOrder) => {
    if (soundEnabled) playSound('click');
    const letter = `PAYPAL DISPUTE EVIDENCE & RESOLUTION DOSSIER
=====================================================
Case Reference: Dispute on Transaction ${order.paypalOrderId}
Internal System ID: ${order.id}
Settlement Value: $${order.totalAmount.toFixed(2)} ${order.currency}
Verified Counterparty: ${order.customerName} (${order.customerEmail})
Capture Timestamp: ${order.timestamp} UTC
APCP Cryptographic Signature: ${order.signatureHash || '0x7e4b...91aa'}

1. CRYPTOGRAPHIC INTENT VERIFICATION:
- Intent Signature Protocol: PayAgent Sentinel Ed25519 Nonce Match
- PayPal API Route: /v2/checkout/orders/${order.paypalOrderId}/capture
- Dispatched Manifest: ${order.itemSummary}

2. AI FRAUD ENGINE DIAGNOSTICS:
- Risk Score at Check-out: ${order.riskScore}/100 (${order.riskLevel})
- Risk Diagnostics: ${order.fraudReasoning || 'Zero anomaly detected. Clean device fingerprint with persistent IP session.'}

3. MERCHANT AFFIDAVIT:
The transaction was executed via autonomous buyer consent with verified PayPal Sandbox checkout callbacks. In accordance with PayPal Seller Protection guidelines, all items have been staged for fulfillment.

Generated by: PayAgent Sentinel Autonomous Intelligence`;
    setGeneratedDispute(letter);
  };

  const copyDispute = () => {
    if (!generatedDispute) return;
    navigator.clipboard.writeText(generatedDispute);
    setCopied(true);
    if (soundEnabled) playSound('click');
    setTimeout(() => setCopied(false), 2000);
  };

  // AG Grid Column Definitions
  const columnDefs = useMemo<ColDef<MerchantOrder>[]>(() => [
    {
      headerName: 'Order ID',
      field: 'id',
      width: 115,
      pinned: 'left',
      cellClass: 'font-mono font-bold text-blue-400',
    },
    {
      headerName: 'PayPal Order ID',
      field: 'paypalOrderId',
      width: 175,
      cellClass: 'font-mono text-xs text-slate-300',
    },
    {
      headerName: 'Customer',
      field: 'customerName',
      width: 165,
      cellRenderer: (params: any) => (
        <div className="py-1">
          <div className="font-bold text-white text-xs truncate">{params.data.customerName}</div>
          <div className="text-[10px] text-slate-400 font-mono truncate">{params.data.customerEmail}</div>
        </div>
      ),
    },
    {
      headerName: 'Item Breakdown',
      field: 'itemSummary',
      flex: 1,
      minWidth: 230,
      cellClass: 'text-xs text-slate-300',
    },
    {
      headerName: 'Amount',
      field: 'totalAmount',
      width: 115,
      valueFormatter: (params) => `$${params.value?.toFixed(2)} USD`,
      cellClass: 'font-mono font-bold text-emerald-400 text-xs',
    },
    {
      headerName: 'APCP Signature',
      field: 'signatureHash',
      width: 135,
      cellRenderer: (params: any) => (
        <span className="font-mono text-[10px] bg-slate-800 text-cyan-300 px-2 py-0.5 rounded border border-white/5">
          {params.value || '0x4f2a...88bc'}
        </span>
      ),
    },
    {
      headerName: 'AI Risk Matrix',
      field: 'riskScore',
      width: 140,
      cellRenderer: (params: any) => {
        const score = params.value;
        const color =
          score > 60
            ? 'bg-rose-500/15 text-rose-300 border-rose-500/30'
            : score > 30
            ? 'bg-amber-500/15 text-amber-300 border-amber-500/30'
            : 'bg-emerald-500/15 text-emerald-300 border-emerald-500/30';
        return (
          <span className={`px-2 py-0.5 rounded-full text-[10.5px] font-mono font-bold border ${color}`}>
            {score}/100 &bull; {score > 60 ? 'HIGH' : score > 30 ? 'MED' : 'LOW'}
          </span>
        );
      },
    },
    {
      headerName: 'Status',
      field: 'status',
      width: 120,
      cellRenderer: (params: any) => {
        const status = params.value;
        const color =
          status === 'FLAGGED'
            ? 'bg-rose-500/20 text-rose-400 border-rose-500/30'
            : 'bg-emerald-500/20 text-emerald-400 border-emerald-500/30';
        return (
          <span className={`px-2 py-0.5 rounded-md text-[10px] font-mono font-black uppercase tracking-wider border ${color}`}>
            {status}
          </span>
        );
      },
    },
    {
      headerName: 'Timestamp (UTC)',
      field: 'timestamp',
      width: 155,
      cellClass: 'font-mono text-[10.5px] text-slate-400',
    },
  ], []);

  const defaultColDef = useMemo<ColDef>(() => ({
    sortable: true,
    filter: true,
    resizable: true,
  }), []);

  const totalVolume = orders.reduce((sum, o) => sum + o.totalAmount, 0);
  const flaggedCount = orders.filter((o) => o.status === 'FLAGGED' || o.riskScore >= 60).length;

  return (
    <div className="max-w-7xl mx-auto px-3 sm:px-6 py-4 sm:py-6 space-y-5">
      
      {/* Top FinTech Telemetry KPI Cards */}
      <div className="grid grid-cols-2 lg:grid-cols-4 gap-3 sm:gap-4">
        
        <div className="glass-panel rounded-2xl sm:rounded-3xl p-4 shadow-xl">
          <div className="flex items-center justify-between">
            <span className="text-[10px] sm:text-[11px] font-mono uppercase tracking-wider text-slate-400 truncate">Settled Volume</span>
            <div className="w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-blue-500/10 border border-blue-500/20 flex items-center justify-center text-blue-400 shrink-0">
              <DollarSign className="w-3.5 h-3.5 sm:w-4 sm:h-4" />
            </div>
          </div>
          <h3 className="text-xl sm:text-2xl font-black text-white font-mono mt-2">${totalVolume.toFixed(2)}</h3>
          <p className="text-[9.5px] sm:text-[10px] text-emerald-400 font-mono mt-1 flex items-center truncate">
            <TrendingUp className="w-3 h-3 mr-1 shrink-0" /> PayPal Orders v2 Sandbox
          </p>
        </div>

        <div className="glass-panel rounded-2xl sm:rounded-3xl p-4 shadow-xl">
          <div className="flex items-center justify-between">
            <span className="text-[10px] sm:text-[11px] font-mono uppercase tracking-wider text-slate-400 truncate">AG Grid Stream</span>
            <div className="w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-indigo-500/10 border border-indigo-500/20 flex items-center justify-center text-indigo-400 shrink-0">
              <CheckCircle className="w-3.5 h-3.5 sm:w-4 sm:h-4" />
            </div>
          </div>
          <h3 className="text-xl sm:text-2xl font-black text-white font-mono mt-2">{orders.length} Rows</h3>
          <p className="text-[9.5px] sm:text-[10px] text-slate-400 font-mono mt-1 truncate">
            {isLiveStreaming ? '⚡ Live stream active' : 'Stream paused'}
          </p>
        </div>

        <div className="glass-panel rounded-2xl sm:rounded-3xl p-4 shadow-xl">
          <div className="flex items-center justify-between">
            <span className="text-[10px] sm:text-[11px] font-mono uppercase tracking-wider text-slate-400 truncate">Flagged Anomalies</span>
            <div className="w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-rose-500/10 border border-rose-500/20 flex items-center justify-center text-rose-400 shrink-0">
              <ShieldAlert className="w-3.5 h-3.5 sm:w-4 sm:h-4" />
            </div>
          </div>
          <h3 className="text-xl sm:text-2xl font-black text-rose-400 font-mono mt-2">{flaggedCount} Orders</h3>
          <p className="text-[9.5px] sm:text-[10px] text-rose-300 font-mono mt-1 flex items-center truncate">
            <AlertTriangle className="w-3 h-3 mr-1 shrink-0" /> Chargeback Shield
          </p>
        </div>

        <div className="glass-panel rounded-2xl sm:rounded-3xl p-4 shadow-xl">
          <div className="flex items-center justify-between">
            <span className="text-[10px] sm:text-[11px] font-mono uppercase tracking-wider text-slate-400 truncate">Sponsor Tech</span>
            <div className="w-7 h-7 sm:w-8 sm:h-8 rounded-xl bg-cyan-500/10 border border-cyan-500/20 flex items-center justify-center text-cyan-400 font-black text-xs font-mono shrink-0">
              AG
            </div>
          </div>
          <h3 className="text-base sm:text-lg font-bold text-white mt-2 truncate">AG Grid Community</h3>
          <p className="text-[9.5px] sm:text-[10px] text-cyan-400 font-mono mt-1 flex items-center truncate">
            <Zap className="w-3 h-3 mr-1 shrink-0" /> Sylwia Vargas Review
          </p>
        </div>

      </div>

      {/* Enterprise AG Grid Container */}
      <div className="glass-panel rounded-3xl p-4 sm:p-5 shadow-2xl space-y-4">
        
        {/* Toolbar with Live Stream Toggle */}
        <div className="flex flex-col sm:flex-row items-stretch sm:items-center justify-between gap-2.5">
          <div className="flex items-center space-x-2">
            <div className="relative flex-1 sm:w-64">
              <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                value={quickFilter}
                onChange={(e) => setQuickFilter(e.target.value)}
                placeholder="AG Grid Quick Filter..."
                className="w-full pl-9 pr-3 py-2 bg-black/40 border border-white/10 rounded-xl text-xs text-white placeholder-slate-500 focus:outline-none focus:border-blue-500 font-mono"
              />
            </div>
            <button
              onClick={() => {
                if (soundEnabled) playSound('click');
                fetchOrders();
              }}
              className="p-2 rounded-xl bg-black/40 border border-white/10 hover:border-white/20 text-slate-300 hover:text-white transition"
              title="Refresh Grid Data"
            >
              <RefreshCw className={`w-4 h-4 ${loading ? 'animate-spin' : ''}`} />
            </button>
          </div>

          <div className="flex flex-wrap items-center gap-2">
            
            {/* Live Stream Simulator Button */}
            <button
              onClick={toggleLiveStream}
              className={`flex items-center space-x-1.5 px-3 py-2 rounded-xl text-xs font-bold font-mono transition border ${
                isLiveStreaming
                  ? 'bg-emerald-500/20 border-emerald-500/40 text-emerald-300 shadow-md shadow-emerald-500/20 animate-pulse'
                  : 'bg-black/40 border-white/10 hover:border-white/20 text-slate-300'
              }`}
            >
              <Radio className={`w-3.5 h-3.5 ${isLiveStreaming ? 'text-emerald-400' : 'text-slate-400'}`} />
              <span>{isLiveStreaming ? 'Streaming Live (1/3.5s)' : 'Simulate Live Stream'}</span>
            </button>

            <button
              onClick={runAiAudit}
              disabled={auditing}
              className="flex items-center justify-center space-x-1.5 px-3.5 py-2 rounded-xl bg-gradient-to-r from-blue-600 to-indigo-600 hover:from-blue-500 hover:to-indigo-500 text-white text-xs font-bold shadow-md shadow-blue-600/30 transition cursor-pointer"
            >
              <Sparkles className="w-3.5 h-3.5" />
              <span className="truncate">{auditing ? 'Auditing...' : 'Run AI Risk Audit'}</span>
            </button>

            <button
              onClick={handleExportCsv}
              className="flex items-center justify-center space-x-1.5 px-3 py-2 rounded-xl bg-black/40 border border-white/10 hover:border-white/20 text-slate-200 text-xs font-semibold transition cursor-pointer"
            >
              <Download className="w-3.5 h-3.5" />
              <span>CSV</span>
            </button>
          </div>
        </div>

        {/* AG Grid React Table */}
        <div className="ag-theme-quartz-dark w-full h-[410px] overflow-hidden shadow-inner">
          <AgGridReact
            ref={gridRef}
            rowData={orders}
            columnDefs={columnDefs}
            defaultColDef={defaultColDef}
            quickFilterText={quickFilter}
            pagination={true}
            paginationPageSize={10}
            rowSelection="single"
            onRowClicked={(event) => {
              if (soundEnabled) playSound('click');
              setSelectedOrder(event.data || null);
            }}
          />
        </div>

      </div>

      {/* AI Deep Inspection & Dispute Copilot */}
      <div className="grid grid-cols-1 lg:grid-cols-2 gap-5">
        
        {/* Selected Order Inspector */}
        <div className="glass-panel rounded-3xl p-5 space-y-4 shadow-xl">
          <div className="flex items-center justify-between pb-3 border-b border-white/5">
            <div className="flex items-center space-x-2">
              <FileText className="w-4 h-4 text-blue-400" />
              <h3 className="text-xs font-black uppercase tracking-wider text-white">
                Order Deep-Inspection &bull; Dispute Defense
              </h3>
            </div>
            {selectedOrder && (
              <span className="font-mono text-xs px-2.5 py-0.5 rounded-lg bg-blue-500/10 text-blue-400 border border-blue-500/20 font-bold">
                {selectedOrder.id}
              </span>
            )}
          </div>

          {selectedOrder ? (
            <div className="space-y-3 text-xs">
              <div className="grid grid-cols-2 gap-2.5 p-3 rounded-2xl bg-black/40 border border-white/5 font-mono">
                <div>
                  <span className="text-slate-400 text-[10px] uppercase">Customer</span>
                  <p className="font-bold text-white text-xs mt-0.5 truncate">{selectedOrder.customerName}</p>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase">PayPal Email</span>
                  <p className="text-slate-300 text-xs mt-0.5 truncate">{selectedOrder.customerEmail}</p>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase">Settled Total</span>
                  <p className="font-black text-emerald-400 text-sm mt-0.5">${selectedOrder.totalAmount.toFixed(2)} USD</p>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase">AI Risk Engine</span>
                  <p className={`font-black text-xs mt-0.5 ${selectedOrder.riskScore > 60 ? 'text-rose-400' : 'text-emerald-400'}`}>
                    {selectedOrder.riskScore}/100 &bull; {selectedOrder.riskLevel}
                  </p>
                </div>
              </div>

              <div>
                <span className="text-slate-400 font-mono text-[10px] uppercase">Autonomous Diagnostic Log:</span>
                <p className="mt-1 p-3 rounded-xl bg-black/50 border border-white/5 text-slate-300 leading-relaxed font-mono text-[11px]">
                  {selectedOrder.fraudReasoning || 'Transaction confirmed clean by autonomous agent pre-flight validation.'}
                </p>
              </div>

              <div className="pt-1">
                <button
                  onClick={() => generateDisputeLetter(selectedOrder)}
                  className="w-full py-2.5 px-4 rounded-xl bg-gradient-to-r from-indigo-600 to-blue-600 hover:from-indigo-500 hover:to-blue-500 text-white font-bold transition flex items-center justify-center space-x-2 shadow-md shadow-indigo-600/20 cursor-pointer active:scale-98"
                >
                  <Sparkles className="w-4 h-4 text-cyan-300" />
                  <span>Generate PayPal Dispute Defense Dossier</span>
                </button>
              </div>

              {generatedDispute && (
                <div className="mt-2.5 p-3.5 rounded-2xl bg-black/80 border border-indigo-500/30 space-y-2 animate-in fade-in duration-200">
                  <div className="flex items-center justify-between text-indigo-400 font-bold text-xs">
                    <span className="flex items-center space-x-1.5">
                      <ShieldCheck className="w-4 h-4 text-emerald-400" />
                      <span>PayPal Legal Evidence Dossier</span>
                    </span>
                    <button
                      onClick={copyDispute}
                      className="flex items-center space-x-1 text-[11px] text-slate-300 hover:text-white bg-slate-800 px-2.5 py-1 rounded-lg border border-slate-700 transition"
                    >
                      {copied ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                      <span>{copied ? 'Copied' : 'Copy'}</span>
                    </button>
                  </div>
                  <pre className="text-[10px] text-slate-300 whitespace-pre-wrap font-mono max-h-44 overflow-y-auto p-2 bg-slate-950 rounded-xl border border-white/5">
                    {generatedDispute}
                  </pre>
                </div>
              )}
            </div>
          ) : (
            <p className="text-xs text-slate-400 py-10 text-center font-mono">
              Select any row in the AG Grid above to inspect risk diagnostics
            </p>
          )}
        </div>

        {/* AI Merchant Audit Recommendations */}
        <div className="glass-panel rounded-3xl p-5 space-y-4 shadow-xl">
          <div className="flex items-center justify-between pb-3 border-b border-white/5">
            <div className="flex items-center space-x-2">
              <Sparkles className="w-4 h-4 text-cyan-400" />
              <h3 className="text-xs font-black uppercase tracking-wider text-white">
                AI Risk &bull; Elasticity Copilot
              </h3>
            </div>
            <span className="text-[9.5px] px-2 py-0.5 rounded-full bg-cyan-500/10 text-cyan-300 border border-cyan-500/20 font-mono font-bold">
              Autonomous
            </span>
          </div>

          {auditData ? (
            <div className="space-y-3">
              <div className="grid grid-cols-3 gap-2 p-3 rounded-2xl bg-black/40 border border-white/5 text-center font-mono text-xs">
                <div>
                  <span className="text-slate-400 text-[10px] uppercase">Audited Vol</span>
                  <p className="font-bold text-white mt-0.5">${auditData.metrics.totalVolume}</p>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase">Flagged Vol</span>
                  <p className="font-bold text-rose-400 mt-0.5">${auditData.metrics.flaggedVolume}</p>
                </div>
                <div>
                  <span className="text-slate-400 text-[10px] uppercase">Risk Ratio</span>
                  <p className="font-bold text-amber-400 mt-0.5">{auditData.metrics.highRiskRatio}</p>
                </div>
              </div>

              <div className="space-y-2">
                {auditData.recommendations.map((rec: any, idx: number) => (
                  <div key={idx} className="p-3 rounded-2xl bg-black/40 border border-white/5 text-xs space-y-1">
                    <div className="flex items-center justify-between">
                      <span className="font-bold text-white text-xs">{rec.title}</span>
                      <span className={`text-[9.5px] px-1.5 py-0.5 rounded font-mono font-bold ${
                        rec.severity === 'HIGH'
                          ? 'bg-rose-500/20 text-rose-300 border border-rose-500/30'
                          : rec.severity === 'MEDIUM'
                          ? 'bg-amber-500/20 text-amber-300 border border-amber-500/30'
                          : 'bg-blue-500/20 text-blue-300 border border-blue-500/30'
                      }`}>
                        {rec.severity}
                      </span>
                    </div>
                    <p className="text-slate-400 leading-relaxed text-[11px]">{rec.description}</p>
                  </div>
                ))}
              </div>
            </div>
          ) : (
            <div className="text-center py-10 space-y-3">
              <Sparkles className="w-8 h-8 text-indigo-400 mx-auto opacity-70 animate-bounce" />
              <p className="text-xs text-slate-400 max-w-sm mx-auto leading-relaxed">
                Click <strong>&quot;Run AI Risk Audit&quot;</strong> to let our autonomous LLM agent evaluate fraud vulnerabilities across all current PayPal transactions in AG Grid.
              </p>
              <button
                onClick={runAiAudit}
                className="px-4 py-2 text-xs font-bold rounded-xl bg-indigo-600 hover:bg-indigo-500 text-white transition shadow-md shadow-indigo-600/30 cursor-pointer"
              >
                Execute Audit Now
              </button>
            </div>
          )}
        </div>

      </div>

    </div>
  );
}
